def main():
    print("Step 1: creating run_expectancy table...")
    Base.metadata.create_all(bind=engine)
    print("Done.")

    print("Step 2: seeding run expectancy data...")
    session = get_session()
    try:
        if session.query(RunExpectancy).count() > 0:
            print("Already seeded -- nothing to do.")
        else:
            session.add_all([
                RunExpectancy(outs=outs, bases=bases, count=count, re_value=re_value)
                for outs, bases, count, re_value in RE_DATA
            ])
            session.commit()
            print(f"Seeded {len(RE_DATA)} run expectancy rows.")
    finally:
        session.close()

    print("\nMigration complete. Existing GamePitch rows are NOT backfilled -- "
          "only pitches logged after this point will have RE/RV computed.")


if __name__ == "__main__":
    main()